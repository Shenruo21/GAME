  const CN = { '一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
               '六': 6, '七': 7, '八': 8, '九': 9, '十': 10 };

  
  function cn(s) {
    if (s === '十') return 10;
    if (s[0] === '十') return 10 + CN[s[1]];
    if (s.length === 1) return CN[s];
    if (s[1] === '十') {
      const t = CN[s[0]] * 10;
      return s.length === 2 ? t : t + CN[s[2]];
    }
    return 0;
  }

  
  let birth = '0427';
  const bd = ((D.myWorld.blocks || []).find(b => /生 日/.test(b.h)) || {}).t || '';
  const m1 = bd.match(/(\d+)\s*月\s*(\d+)/);
  if (m1) birth = pad(m1[1]) + pad(m1[2]);

  
  let night = '0814';
  const pk = ((D.town.park.notices || []).find(r => /河灯节/.test(r[1])) || [])[1] || '';
